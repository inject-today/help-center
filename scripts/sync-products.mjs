// Checks src/data/products.json and regenerates the files that list every
// product (the "Report a fix" form). Run `npm run sync` after editing the list;
// CI runs `npm run sync:check`, which fails if they are out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { loadProducts, ROOT, validateProducts } from './lib/products.mjs';

const check = process.argv.includes('--check');
const products = loadProducts();

const problems = validateProducts(products);
if (problems.length > 0) {
	console.error(`The product list has problems:\n- ${problems.join('\n- ')}`);
	process.exit(1);
}

const names = products
	.map((p) => p.name)
	.toSorted((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }));

const yamlString = (value) => JSON.stringify(value);

const fixReportForm = `# Generated by scripts/sync-products.mjs from src/data/products.json; edit those instead.
name: Report a fix
description: Tell us about a fix that isn't on the site yet. A moderator will turn it into a guide.
title: "[Fix] "
labels: [fix-report]
body:
  - type: markdown
    attributes:
      value: |
        Thanks for helping. Describe the problem and how you fixed it, and a moderator will write it up as a guide.
        Don't include keys, license codes, account details or anything else personal.
  - type: dropdown
    id: product
    attributes:
      label: Product
      options:
${names.map((name) => `        - ${yamlString(name)}`).join('\n')}
        - "Other / not listed"
    validations:
      required: true
  - type: input
    id: version
    attributes:
      label: Product version
      description: If you know it.
  - type: textarea
    id: symptom
    attributes:
      label: What went wrong?
      description: The exact error message, or what happened and when.
    validations:
      required: true
  - type: textarea
    id: fix
    attributes:
      label: How did you fix it?
      description: Step by step, as if explaining it to someone new.
    validations:
      required: true
  - type: input
    id: verified
    attributes:
      label: When did you last confirm this works?
      placeholder: "2026-10-26"
  - type: textarea
    id: source
    attributes:
      label: Source
      description: If someone else found this fix, credit them or link where it came from.
  - type: checkboxes
    id: rules
    attributes:
      label: Before you send it
      options:
        - label: Any download links point to the product's official website or Discord, and there are no keys or personal information in this report.
          required: true
`;

const outputs = [{ path: '.github/ISSUE_TEMPLATE/fix-report.yml', content: fixReportForm }];

let stale = 0;
for (const { path, content } of outputs) {
	const url = new URL(path, ROOT);
	let current = '';
	try {
		current = readFileSync(url, 'utf8').replace(/\r\n/g, '\n');
	} catch {}
	if (current === content) continue;
	if (check) {
		console.error(`${path} is out of date. Run \`npm run sync\` and commit the result.`);
		stale++;
	} else {
		writeFileSync(url, content);
		console.log(`Updated ${path}`);
	}
}

if (stale > 0) process.exit(1);
console.log(`${products.length} products OK.`);
